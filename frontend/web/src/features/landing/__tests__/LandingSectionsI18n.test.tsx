import { describe, it, expect, afterEach } from "vitest";
import { screen } from "@testing-library/react";
import { useTranslationStore } from "@/stores/useTranslationStore";
import { renderWithProviders } from "@/test/renderWithProviders";
import LandingPage from "../pages/LandingPage";

// English copy of the hero, features, how-it-works and CTA sections.
const ENGLISH_COPY = [
  /Plan Your Perfect Journey/,
  /Intelligent travel planning powered by AI/,
  /Get Started Free/,
  /Everything you need to plan perfectly/,
  /we've got you covered/,
  /AI-Powered Planning/,
  /Get personalized itineraries generated by AI/,
  /Interactive Maps/,
  /Visualize your journey with Mapbox/,
  /Smart Budgeting/,
  /Track expenses, set limits/,
  /^How it works$/,
  /Get started in minutes/,
  /^Sign up$/,
  /Create your free account/,
  /^Plan with AI$/,
  /Chat with our AI/,
  /^Customize$/,
  /Fine-tune routes/,
  /^Travel$/,
  /Export or share your perfect travel plan/,
  /Ready to start planning\?/,
  /plan smarter with AI/,
];

describe("Landing sections translations", () => {
  afterEach(() => {
    useTranslationStore.setState({ language: "English (US)" });
  });

  it("keeps the English copy in English", () => {
    renderWithProviders(<LandingPage />);
    expect(
      screen.getByRole("heading", { level: 1, name: /Plan Your Perfect/ }),
    ).toBeInTheDocument();
    expect(screen.getAllByText(/Get Started Free/)).toHaveLength(2);
    expect(
      screen.getByRole("heading", { name: "How it works" }),
    ).toBeInTheDocument();
  });

  it.each(["French", "Vietnamese"] as const)(
    "shows no English section copy in %s",
    (language) => {
      useTranslationStore.setState({ language });
      renderWithProviders(<LandingPage />);
      for (const copy of ENGLISH_COPY) {
        expect(screen.queryAllByText(copy), String(copy)).toHaveLength(0);
      }
    },
  );

  it.each([
    ["French", "Commencer gratuitement"],
    ["Vietnamese", "Bắt đầu miễn phí"],
  ] as const)("labels both sign-up CTAs in %s", (language, label) => {
    useTranslationStore.setState({ language });
    renderWithProviders(<LandingPage />);
    expect(screen.getAllByRole("button", { name: label })).toHaveLength(2);
  });
});
